import { chromium } from '@playwright/test';
const out = 'C:/Users/MIC lunchinm/Desktop/学习资料/Vibe-Coding/合理膳食/文档/out';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
p.on('response', (r) => { if (r.status() >= 400) console.log('HTTP', r.status(), r.url().slice(-60)); });
await p.goto('http://127.0.0.1:8082/');
await p.waitForTimeout(3000);
await p.mouse.click(640, 360);
await p.waitForTimeout(1200);
const jsClick = (label) => p.evaluate((l) => {
  const el = [...document.querySelectorAll('button,div,span,a')].filter((e) => e.textContent.trim() === l);
  const last = el[el.length - 1]; if (!last) return false;
  (last.closest('button') ?? last).dispatchEvent(new MouseEvent('click', { bubbles: true })); return true;
}, label);
await jsClick('简体中文');
await p.waitForTimeout(1500);
await jsClick('开始游戏');
await p.waitForTimeout(12000);
await p.screenshot({ path: out + '/wg8-loaded.png' });
const t = (await p.locator('body').innerText()).replace(/\s+/g, ' ');
console.log('len', t.length, '| tail:', t.slice(-120));
await b.close();