import { chromium } from '@playwright/test';
const out = 'C:/Users/MIC lunchinm/Desktop/学习资料/Vibe-Coding/合理膳食/文档/out';
const b = await chromium.launch();
const ctx = await b.newContext({ serviceWorkers: 'block', viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:8081/index.html');
await p.waitForTimeout(3000);
await p.getByText('简体中文', { exact: true }).first().click({ force: true });
await p.waitForTimeout(2500);
await p.screenshot({ path: out + '/wg-title-cn.png' });
console.log('after lang:', (await p.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 80));
const start = p.getByText('开始游戏').first();
if (await start.count()) await start.click({ force: true });
await p.waitForTimeout(2500);
await p.screenshot({ path: out + '/wg-play.png' });
console.log('after start:', (await p.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 100));
await b.close();