import { chromium } from '@playwright/test';
const out = 'C:/Users/MIC lunchinm/Desktop/学习资料/Vibe-Coding/合理膳食/文档/out';
const b = await chromium.launch();
const ctx = await b.newContext({ serviceWorkers: 'block', viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:8081/index.html');
await p.waitForTimeout(3000);
const clicked = await p.evaluate(() => {
  const wrap = document.querySelector('[class*=langWrapper]');
  if (!wrap) return 'no wrapper';
  const btn = [...wrap.querySelectorAll('*')].find((e) => e.textContent.trim() === '简体中文');
  if (!btn) return 'no button';
  (btn.closest('button') ?? btn).click();
  return 'clicked';
});
console.log(clicked);
await p.waitForTimeout(2500);
await p.screenshot({ path: out + '/wg-after-lang.png' });
console.log('body:', (await p.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 90));
await b.close();