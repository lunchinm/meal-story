import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ serviceWorkers: 'block', viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
p.on('request', (r) => { if (/userStyleSheet|template/i.test(r.url())) console.log('REQ', r.url().slice(-60)); });
p.on('response', (r) => { if (/userStyleSheet|template/i.test(r.url())) console.log('RES', r.status(), r.url().slice(-60)); });
await p.goto('http://127.0.0.1:8082/?n=' + Date.now());
await p.waitForTimeout(4000);
const has = await p.evaluate(() => [...document.styleSheets].map((s) => s.href || 'inline').slice(0, 12));
console.log('sheets:', JSON.stringify(has));
await b.close();