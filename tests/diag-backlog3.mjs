import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ serviceWorkers: 'block', viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:8123/?t=' + Date.now());
await p.waitForTimeout(4200);
await p.evaluate(() => document.querySelector('#paper-title .pt-menu button[data-label="开始游戏"]').click());
await p.waitForTimeout(6500);
for (let i = 0; i < 5; i += 1) { await p.mouse.click(800, 700); await p.waitForTimeout(600); }
const before = await p.evaluate(() => window.__paperLine || '');
await p.evaluate(() => [...document.querySelectorAll('#paper-nav button')].find((x) => x.textContent === '上一句').click());
await p.waitForTimeout(1400);
console.log('回退:', before.slice(0,12), '→', (await p.evaluate(() => window.__paperLine || '')).slice(0,12));
await p.evaluate(() => window.__wgOpenBacklog());
await p.waitForTimeout(800);
const opened = await p.evaluate(() => { const e = document.querySelector('[class*="Backlog_main"]'); return e ? e.className.toString().slice(0, 60) : 'none'; });
await p.evaluate(() => window.__wgClosePanels());
await p.waitForTimeout(900);
const closed = await p.evaluate(() => { const e = document.querySelector('[class*="Backlog_main"]'); return e ? e.className.toString().slice(0, 60) : 'none'; });
console.log('回想打开时:', opened);
console.log('返回后:', closed);
await b.close();