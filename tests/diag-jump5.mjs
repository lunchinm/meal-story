import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ serviceWorkers: 'block', viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
p.on('console', (m) => { const t = m.text(); if (/scene|场景|error/i.test(t)) console.log('LOG:', t.slice(0, 120)); });
await p.goto('http://127.0.0.1:8123/?t=' + Date.now());
await p.waitForTimeout(4000);
await p.evaluate(() => document.querySelector('#paper-title .pt-menu button[data-label="开始游戏"]').click());
await p.waitForTimeout(8000);
for (let i = 0; i < 3; i += 1) await p.mouse.click(800, 700) || await p.waitForTimeout(500);
await p.waitForTimeout(1500);
console.log('当前:', (await p.evaluate(() => window.__paperLine || '')).slice(0, 14));
const r = await p.evaluate(() => window.__wgJump('seg1_2'));
await p.waitForTimeout(2500);
console.log('同场景跳转返回:', r, '现在:', (await p.evaluate(() => window.__paperLine || '')).slice(0, 18));
await b.close();