import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ serviceWorkers: 'block', viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:8082/?t=' + Date.now());
await p.waitForTimeout(2500);
await p.evaluate(() => document.querySelector('#paper-title .pt-menu button[data-label="开始游戏"]').click());
await p.waitForTimeout(6000);
const btns = await p.evaluate(() => [...document.querySelectorAll('[class*="_singleButton"]')].map((e) => ({ cls: e.className.toString().slice(0, 30), txt: (e.innerText || '').replace(/\s+/g, ''), aria: e.getAttribute('aria-label') || '', tag: e.tagName })));
console.log(JSON.stringify(btns).slice(0, 700));
await b.close();